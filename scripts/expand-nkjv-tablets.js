#!/usr/bin/env node
/* Step 5: give every NKJV tablet blank the same six-tablet tray as the KJV.
   The NKJV bank ships three curated decoys per blank; this expands each blank
   with the KJV's curated decoys for the same chapter and blank position, then
   with decoys from the same chapter. No new wording is invented, and the
   answer/duplicate filters keep the tray valid.

   Run: node scripts/expand-nkjv-tablets.js
   The licensed source dump is not in this checkout, so this is the
   reproducible expansion pass; build-nkjv.js still owns the wording. */
const fs = require("fs");
const path = require("path");
const ROOT = require("./repo-root");
const { Tablets } = require("../js/tablets.js");
require("../js/tablets-canon.js");
require("../js/tablets-hall.js");
require("../js/tablets-more.js");
const { NKJV_TABLETS } = require("../js/nkjv/tablets.js");

const KJV = {};
Tablets.chapters.forEach(function(ch){ KJV[ch.id] = ch; });

const globalPool = [];
Tablets.chapters.forEach(function(ch){
  ch.blanks.forEach(function(blank){ (blank.d || []).forEach(function(word){ globalPool.push(word); }); });
});

/* R5: an added decoy must look like the answer and must not be a word the line already shows: the same number of
   words as the answer, not made only of the verse's own words, and not the KJV answer for the same blank. */
function wordsOf(text){
  return String(text || "").toLowerCase().replace(/[^a-z' ]/g, " ").split(/\s+/).filter(Boolean);
}
function decoyFits(word, blank, kjvAnswer, verseWords, anyLength){
  const parts = wordsOf(word);
  if(!anyLength && parts.length !== wordsOf(blank.a).length) return false;
  if(parts.every(function(w){ return verseWords[w]; })) return false;
  return !kjvAnswer || word.toLowerCase() !== kjvAnswer;
}

/* The bank's three curated decoys are the first three; the pass is rerunnable, so it rebuilds the rest each time. */
const CURATED = 3;
/* Multi-word answers ("your dwelling place") rarely find a same-length KJV decoy, so the last source is the NKJV
   bank's own answers and curated decoys from other blanks: still existing wording, none invented. */
const nkjvPool = [];
NKJV_TABLETS.chapters.forEach(function(ch){
  ch.blanks.forEach(function(blank){
    nkjvPool.push(blank.a);
    (blank.d || []).slice(0, CURATED).forEach(function(word){ nkjvPool.push(word); });
  });
});
let added = 0;
let blanks = 0;
let short = 0;
const loose = [];
NKJV_TABLETS.chapters.forEach(function(ch){
  const kjv = KJV[ch.id];
  const chapterPool = [];
  if(kjv){
    kjv.blanks.forEach(function(blank){ (blank.d || []).forEach(function(word){ chapterPool.push(word); }); });
  }
  ch.blanks.forEach(function(blank, i){
    blanks++;
    blank.d = (blank.d || []).slice(0, CURATED);
    const have = {};
    have[String(blank.a || "").toLowerCase()] = true;
    blank.d.forEach(function(word){ have[String(word).toLowerCase()] = true; });
    const verseWords = {};
    wordsOf(blank.prefix + " " + blank.suffix).forEach(function(w){ verseWords[w] = true; });
    const kjvAnswer = (kjv && kjv.blanks[i]) ? String(kjv.blanks[i].a || "").toLowerCase() : "";
    const sources = [];
    if(kjv && kjv.blanks[i]) sources.push.apply(sources, kjv.blanks[i].d || []);
    sources.push.apply(sources, chapterPool);
    sources.push.apply(sources, globalPool);
    sources.push.apply(sources, nkjvPool);
    /* Pass 1 keeps the answer's length. Pass 2 only runs for a blank whose answer no decoy anywhere matches in
       length (the few long NKJV answers such as "steadfast forever; His kingdom is"); it is counted below. */
    [false, true].forEach(function(anyLength){
      const before = blank.d.length;
      for(let s = 0; s < sources.length && blank.d.length < 5; s++){
        const word = String(sources[s] || "").trim();
        const low = word.toLowerCase();
        if(!word || have[low] || !decoyFits(word, blank, kjvAnswer, verseWords, anyLength)) continue;
        have[low] = true;
        blank.d.push(word);
        added++;
      }
      if(anyLength && blank.d.length > before) loose.push(ch.id + " " + blank.r + " \"" + blank.a + "\"");
    });
    if(blank.d.length < 5) short++;
  });
});
if(short) throw new Error(short + " NKJV blanks could not reach five fitting decoys");
if(loose.length) console.log(loose.length + " long answers have no same-length decoy anywhere; filled by meaning only:\n  " + loose.join("\n  "));

const header = "/* GENERATED by scripts/build-nkjv.js from the licensed NKJV text in\n" +
  "   content/nkjv/source/. Do not edit by hand \u2014 rerun the generator.\n" +
  "   the 144 tablet chapters */\n";
const body = JSON.stringify(NKJV_TABLETS, null, 2);
const out = header + "const NKJV_TABLETS = " + body + ";\n" +
  "if(typeof module !== \"undefined\") module.exports = { NKJV_TABLETS };\n";
fs.writeFileSync(path.join(ROOT, "js", "nkjv", "tablets.js"), out);
console.log("added " + added + " decoys across " + blanks + " NKJV tablet blanks");
