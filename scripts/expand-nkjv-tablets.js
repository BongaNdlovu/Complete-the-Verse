#!/usr/bin/env node
/* Step 5: give every NKJV tablet blank the same six-tablet tray as the KJV.
   The NKJV bank ships three curated decoys per blank; this expands each blank
   with the KJV's curated decoys for the same chapter and blank position, then
   with decoys from the same chapter. No new wording is invented, and the
   answer/duplicate filters keep the tray valid.

   Run: node scripts/expand-nkjv-tablets.js
   The licensed source dump is not in this checkout, so this is the
   reproducible expansion pass; build-nkjv.js still owns the wording. */
const fs = require("fs");
const path = require("path");
const ROOT = require("./repo-root");
const { Tablets } = require("../js/tablets.js");
require("../js/tablets-canon.js");
require("../js/tablets-hall.js");
require("../js/tablets-more.js");
const { NKJV_TABLETS } = require("../js/nkjv/tablets.js");

const KJV = {};
Tablets.chapters.forEach(function(ch){ KJV[ch.id] = ch; });

const globalPool = [];
Tablets.chapters.forEach(function(ch){
  ch.blanks.forEach(function(blank){ (blank.d || []).forEach(function(word){ globalPool.push(word); }); });
});

let added = 0;
let blanks = 0;
NKJV_TABLETS.chapters.forEach(function(ch){
  const kjv = KJV[ch.id];
  const chapterPool = [];
  if(kjv){
    kjv.blanks.forEach(function(blank){ (blank.d || []).forEach(function(word){ chapterPool.push(word); }); });
  }
  ch.blanks.forEach(function(blank, i){
    blanks++;
    const have = {};
    have[String(blank.a || "").toLowerCase()] = true;
    (blank.d || []).forEach(function(word){ have[String(word).toLowerCase()] = true; });
    const sources = [];
    if(kjv && kjv.blanks[i]) sources.push.apply(sources, kjv.blanks[i].d || []);
    sources.push.apply(sources, chapterPool);
    sources.push.apply(sources, globalPool);
    for(let s = 0; s < sources.length && (blank.d || []).length < 5; s++){
      const word = String(sources[s] || "").trim();
      const low = word.toLowerCase();
      if(!word || have[low]) continue;
      have[low] = true;
      blank.d.push(word);
      added++;
    }
  });
});

const header = "/* GENERATED by scripts/build-nkjv.js from the licensed NKJV text in\n" +
  "   content/nkjv/source/. Do not edit by hand \u2014 rerun the generator.\n" +
  "   the 144 tablet chapters */\n";
const body = JSON.stringify(NKJV_TABLETS, null, 2);
const out = header + "const NKJV_TABLETS = " + body + ";\n" +
  "if(typeof module !== \"undefined\") module.exports = { NKJV_TABLETS };\n";
fs.writeFileSync(path.join(ROOT, "js", "nkjv", "tablets.js"), out);
console.log("added " + added + " decoys across " + blanks + " NKJV tablet blanks");
