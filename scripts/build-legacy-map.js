#!/usr/bin/env node
/* Emits js/legacy-ids.js — the bridge that lets a v2 save (whose verse
   stats were keyed by array index) keep its progress now that ids are
   derived from the reference and the blank.

   Input is content/legacy-order.json, the snapshot of the v2 bank order
   taken before this release cut anything. Slot i held the verse at
   VERSES[i]; if that verse is still in the bank, slot i maps to its new
   id, otherwise null.

     node scripts/build-legacy-map.js
*/
const fs = require("fs");
const path = require("path");
const { loadBank } = require("./load-bank");
const QA = require("./verse-qa");

const legacy = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "content", "legacy-order.json"), "utf8"));
const bank = loadBank();

const byKey = new Map();
bank.VERSES.forEach(v => byKey.set(QA.norm(v.r) + "||" + QA.norm(v.a), v.id));

let hit = 0;
const table = legacy.map(old => {
  const id = byKey.get(QA.norm(old.r) + "||" + QA.norm(old.a));
  if(id) hit++;
  return id || null;
});

const out = "/* Generated by scripts/build-legacy-map.js — do not edit by hand.\n" +
  "   Index = the verse id a v2 save used; value = the stable id it maps to now,\n" +
  "   or null if that verse was quarantined. " + hit + " of " + legacy.length + " carried over. */\n" +
  "const LEGACY_ID_TABLE = " + JSON.stringify(table) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "js", "legacy-ids.js"), out);

console.log("legacy slots: " + legacy.length + " -> " + hit + " mapped, " + (legacy.length - hit) + " dropped");
