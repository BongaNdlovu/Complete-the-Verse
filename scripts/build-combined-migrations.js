#!/usr/bin/env node
/* Builds supabase/combined_migrations.sql from supabase/migrations/*.sql, in file-name order (the order the
   Supabase CLI applies them), so the one-paste bundle for the SQL Editor cannot drift from the real migrations.

     node scripts/build-combined-migrations.js           write the bundle
     node scripts/build-combined-migrations.js --check   exit 1 when the bundle on disk is stale  */
const fs = require("fs");
const path = require("path");
const ROOT = require("./repo-root");

const MIGRATIONS_DIR = path.join(ROOT, "supabase", "migrations");
const COMBINED_FILE = path.join(ROOT, "supabase", "combined_migrations.sql");
const RULE = "-- ==========================================";

function lf(text) {
  return text.replace(/\r\n/g, "\n");
}

function migrationFiles() {
  return fs.readdirSync(MIGRATIONS_DIR).filter(function (name) { return name.endsWith(".sql"); }).sort();
}

function build() {
  const files = migrationFiles();
  const parts = [
    "-- Complete the Verse — Combined Supabase Migrations (" + files.length + " files, generated)",
    "-- Generated by scripts/build-combined-migrations.js from supabase/migrations/. Do not edit by hand:",
    "-- change a migration, then run `npm run db:combine`.",
    ""
  ];
  files.forEach(function (name) {
    const body = lf(fs.readFileSync(path.join(MIGRATIONS_DIR, name), "utf8")).replace(/\n+$/, "");
    parts.push(RULE, "-- FILE: " + name, RULE, body, "");
  });
  return parts.join("\n");
}

function isFresh() {
  if (!fs.existsSync(COMBINED_FILE)) return false;
  return lf(fs.readFileSync(COMBINED_FILE, "utf8")) === build();
}

if (require.main === module) {
  if (process.argv.includes("--check")) {
    if (isFresh()) {
      console.log("combined_migrations.sql is up to date with " + migrationFiles().length + " migrations");
      process.exit(0);
    }
    console.error("combined_migrations.sql is stale: run `npm run db:combine`");
    process.exit(1);
  }
  fs.writeFileSync(COMBINED_FILE, build());
  console.log("wrote supabase/combined_migrations.sql from " + migrationFiles().length + " migrations");
}

module.exports = { build, isFresh, migrationFiles };
